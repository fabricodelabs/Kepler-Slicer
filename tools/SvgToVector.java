import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.*;
import java.util.regex.*;

/**
 * Converts the flat Figma SVG exports (path/rect/circle/ellipse with solid fills and strokes)
 * into Android VectorDrawable XML without altering geometry. Gradients are rejected.
 *
 * Usage: java tools/SvgToVector.java <out-dir> <name>=<file.svg> ...
 */
public class SvgToVector {
    private static final Pattern TAG = Pattern.compile("<(/?)([a-zA-Z]+)([^>]*?)(/?)>", Pattern.DOTALL);
    private static final Pattern ATTR = Pattern.compile("([a-zA-Z:-]+)=\"([^\"]*)\"");

    public static void main(String[] args) throws Exception {
        if (args.length < 2) throw new IllegalArgumentException("usage: <out-dir> name=file.svg ...");
        Path out = Paths.get(args[0]);
        Files.createDirectories(out);
        for (int i = 1; i < args.length; i++) {
            String[] pair = args[i].split("=", 2);
            String xml = convert(new String(Files.readAllBytes(Paths.get(pair[1])), StandardCharsets.UTF_8));
            Files.write(out.resolve(pair[0] + ".xml"), xml.getBytes(StandardCharsets.UTF_8));
            System.out.println("wrote " + pair[0] + ".xml");
        }
    }

    static Map<String, String> attrs(String s) {
        Map<String, String> m = new LinkedHashMap<>();
        Matcher a = ATTR.matcher(s);
        while (a.find()) m.put(a.group(1), a.group(2));
        return m;
    }

    static String convert(String svg) {
        if (svg.contains("Gradient")) throw new IllegalArgumentException("gradients are not supported");
        StringBuilder body = new StringBuilder();
        Deque<Map<String, String>> groups = new ArrayDeque<>();
        String w = null, h = null, vb = null;
        Matcher t = TAG.matcher(svg);
        while (t.find()) {
            boolean close = !t.group(1).isEmpty(), self = !t.group(4).isEmpty();
            String name = t.group(2);
            Map<String, String> a = attrs(t.group(3));
            if (name.equals("svg") && !close) { w = a.get("width"); h = a.get("height"); vb = a.get("viewBox"); continue; }
            if (name.equals("g")) { if (close) groups.pop(); else if (!self) groups.push(a); continue; }
            if (close) continue;
            Map<String, String> eff = new HashMap<>();
            List<Map<String, String>> chain = new ArrayList<>(groups);
            Collections.reverse(chain);
            for (Map<String, String> g : chain) for (Map.Entry<String, String> e : g.entrySet()) if (!e.getKey().equals("id")) eff.put(e.getKey(), e.getValue());
            eff.putAll(a);
            if (eff.containsKey("transform")) throw new IllegalArgumentException("transforms are not supported");
            String d;
            switch (name) {
                case "path": d = a.get("d"); break;
                case "rect": d = rect(a); break;
                case "circle": d = ellipse(num(a.get("cx")), num(a.get("cy")), num(a.get("r")), num(a.get("r"))); break;
                case "ellipse": d = ellipse(num(a.get("cx")), num(a.get("cy")), num(a.get("rx")), num(a.get("ry"))); break;
                default: continue;
            }
            body.append("    <path\n        android:pathData=\"").append(d).append('"');
            String fill = eff.get("fill");
            if (fill != null && !fill.equals("none")) {
                body.append("\n        android:fillColor=\"").append(color(fill, eff.get("fill-opacity"), eff.get("opacity"))).append('"');
                if ("evenodd".equals(eff.get("fill-rule"))) body.append("\n        android:fillType=\"evenOdd\"");
            }
            String stroke = eff.get("stroke");
            if (stroke != null && !stroke.equals("none")) {
                body.append("\n        android:strokeColor=\"").append(color(stroke, eff.get("stroke-opacity"), eff.get("opacity"))).append('"');
                body.append("\n        android:strokeWidth=\"").append(eff.getOrDefault("stroke-width", "1")).append('"');
                if (eff.containsKey("stroke-linecap")) body.append("\n        android:strokeLineCap=\"").append(eff.get("stroke-linecap")).append('"');
                if (eff.containsKey("stroke-linejoin")) body.append("\n        android:strokeLineJoin=\"").append(eff.get("stroke-linejoin")).append('"');
            }
            body.append(" />\n");
        }
        String[] box = vb == null ? new String[]{"0", "0", w, h} : vb.trim().split("\\s+");
        if (!box[0].equals("0") || !box[1].equals("0")) throw new IllegalArgumentException("viewBox origin must be 0 0");
        return "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by tools/SvgToVector.java from the Kepler Glass UI v3 Figma export. -->\n"
            + "<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"\n    android:width=\"" + w + "dp\"\n    android:height=\"" + h + "dp\"\n"
            + "    android:viewportWidth=\"" + box[2] + "\"\n    android:viewportHeight=\"" + box[3] + "\">\n" + body + "</vector>\n";
    }

    static double num(String s) { return s == null ? 0 : Double.parseDouble(s); }
    static String f(double v) { String s = String.format(Locale.ROOT, "%.4f", v); s = s.replaceAll("0+$", ""); return s.endsWith(".") ? s.substring(0, s.length() - 1) : s; }

    static String rect(Map<String, String> a) {
        double x = num(a.get("x")), y = num(a.get("y")), w = num(a.get("width")), h = num(a.get("height"));
        double rx = a.containsKey("rx") ? num(a.get("rx")) : num(a.get("ry")), ry = a.containsKey("ry") ? num(a.get("ry")) : rx;
        rx = Math.min(rx, w / 2); ry = Math.min(ry, h / 2);
        if (rx <= 0) return "M" + f(x) + "," + f(y) + "H" + f(x + w) + "V" + f(y + h) + "H" + f(x) + "Z";
        return "M" + f(x + rx) + "," + f(y) + "H" + f(x + w - rx) + "A" + f(rx) + "," + f(ry) + " 0 0 1 " + f(x + w) + "," + f(y + ry)
            + "V" + f(y + h - ry) + "A" + f(rx) + "," + f(ry) + " 0 0 1 " + f(x + w - rx) + "," + f(y + h)
            + "H" + f(x + rx) + "A" + f(rx) + "," + f(ry) + " 0 0 1 " + f(x) + "," + f(y + h - ry)
            + "V" + f(y + ry) + "A" + f(rx) + "," + f(ry) + " 0 0 1 " + f(x + rx) + "," + f(y) + "Z";
    }

    static String ellipse(double cx, double cy, double rx, double ry) {
        return "M" + f(cx - rx) + "," + f(cy) + "A" + f(rx) + "," + f(ry) + " 0 1 0 " + f(cx + rx) + "," + f(cy)
            + "A" + f(rx) + "," + f(ry) + " 0 1 0 " + f(cx - rx) + "," + f(cy) + "Z";
    }

    static String color(String c, String opacity, String groupOpacity) {
        String hex;
        if (c.equalsIgnoreCase("white")) hex = "FFFFFF";
        else if (c.equalsIgnoreCase("black")) hex = "000000";
        else if (c.matches("#[0-9a-fA-F]{6}")) hex = c.substring(1).toUpperCase(Locale.ROOT);
        else if (c.matches("#[0-9a-fA-F]{3}")) { String s = c.substring(1); hex = ("" + s.charAt(0) + s.charAt(0) + s.charAt(1) + s.charAt(1) + s.charAt(2) + s.charAt(2)).toUpperCase(Locale.ROOT); }
        else throw new IllegalArgumentException("unsupported color " + c);
        double alpha = (opacity == null ? 1 : num(opacity)) * (groupOpacity == null ? 1 : num(groupOpacity));
        if (alpha >= 0.999) return "#" + hex;
        return String.format(Locale.ROOT, "#%02X%s", (int) Math.round(alpha * 255), hex);
    }
}
