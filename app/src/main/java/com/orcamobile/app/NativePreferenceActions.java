package com.orcamobile.app;

import android.content.Context;
import android.os.Looper;
import android.util.AtomicFile;
import com.keplerslicer.engine.ExperimentalSlicer;
import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.InterruptedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.Locale;
import org.json.JSONArray;
import org.json.JSONObject;

/** Worker operations connecting Preferences to detached native model/config work. */
final class NativePreferenceActions {
    private NativePreferenceActions() {}

    /**
     * Clone an immutable plain-model snapshot, then publish only while the same
     * model, placement, plate, profiles and overrides are still selected.
     * Embedded 3MF projects require a separate faithful project-session export.
     */
    static String clonePlainModel(Context context, int copies, boolean arrange) throws IOException {
        requireWorker();
        final Context app = context.getApplicationContext();
        if (copies <= 0) throw new IOException(app.getString(R.string.native_actions_positive_count));
        interrupted(app);
        final CurrentModelStore.RestoreSelection expected = CurrentModelStore.captureRestoreSelection(app);
        final EngineProfileSession session = EngineProfileSession.capture(app);
        final File staging = Files.createTempDirectory(app.getCacheDir().toPath(), "native-clone-").toFile();
        final File job = session.newJob("clone");
        try {
            final CurrentModelStore.Snapshot source = CurrentModelStore.snapshotToDirectory(app, staging);
            final String suffix = source.file.getName().toLowerCase(Locale.ROOT);
            if (!suffix.endsWith(".stl") && !suffix.endsWith(".obj"))
                throw new IOException(app.getString(R.string.native_actions_project_clone_unsupported));
            requireUnchanged(app, source, session);
            final ProcessOverridesStore.Identity id = session.id;
            final String result = ExperimentalSlicer.cloneModelWithPreferences(
                id.printer.vendor, id.process.vendor, id.filament.vendor,
                id.printerName, id.processName, id.filamentName,
                source.file.getAbsolutePath(), session.resources.getAbsolutePath(), session.data.getAbsolutePath(),
                job.getAbsolutePath(), source.transform.toNativeArguments(), session.selection.overrides,
                0, 0, copies, arrange);
            interrupted(app);
            if (result == null || result.isEmpty()) throw new IOException(app.getString(R.string.native_actions_invalid_result));
            final File derived = new File(result).getCanonicalFile();
            if (!job.getCanonicalFile().equals(derived.getParentFile()) ||
                !derived.getName().toLowerCase(Locale.ROOT).endsWith(".3mf") || !derived.isFile() || derived.length() == 0)
                throw new IOException(app.getString(R.string.native_actions_invalid_result));
            requireUnchanged(app, source, session);
            final String name = cloneName(app, source.name);
            ProcessOverridesStore.changeSelection(app, false, () -> {
                interrupted(app);
                if (!session.stillCurrent(app)) throw new IOException(app.getString(R.string.native_actions_profiles_changed));
                CurrentModelStore.replaceDerived(app, derived, name, expected);
            });
            return name;
        } catch (LinkageError e) {
            throw new IOException(app.getString(R.string.native_actions_engine_unavailable), e);
        } catch (RuntimeException e) {
            throw new IOException(app.getString(R.string.native_actions_native_error, message(e)), e);
        } finally {
            // Both paths were generated by this operation under app-private
            // cache/data roots. The published model is a separate validated copy.
            deletePrivateJob(staging);
            deletePrivateJob(job);
        }
    }

    static String runSelfTest(Context context) throws IOException {
        requireWorker();
        final Context app = context.getApplicationContext();
        interrupted(app);
        EngineProfileSession session = EngineProfileSession.capture(app);
        try {
            byte[] result = ExperimentalSlicer.runNativePreferencesSelfTest(
                session.resources.getAbsolutePath(), session.data.getAbsolutePath());
            if (result == null || result.length == 0) throw new IOException(app.getString(R.string.native_actions_invalid_result));
            interrupted(app);
            JSONObject report=new JSONObject(new String(result,StandardCharsets.UTF_8));JSONArray checks=report.getJSONArray("checks");int count=report.getInt("count");
            if(!report.getBoolean("passed")||count!=checks.length())throw new IOException(app.getString(R.string.native_actions_invalid_result));
            StringBuilder readable=new StringBuilder(app.getString(R.string.native_preferences_test_passed,count)).append("\n\n");
            for(int i=0;i<count;i++){JSONObject check=checks.getJSONObject(i);if(!check.getBoolean("passed")||check.getString("name").isEmpty())throw new IOException(app.getString(R.string.native_actions_invalid_result));readable.append("✓ ").append(check.getString("name")).append('\n');}
            File directory=new File(app.getFilesDir(),"slicer-engine");if(!directory.isDirectory()&&!directory.mkdirs())throw new IOException(app.getString(R.string.native_preferences_test_report_failed));
            AtomicFile saved=new AtomicFile(new File(directory,"native-preferences-checks.json"));FileOutputStream output=null;
            try{output=saved.startWrite();output.write(result);interrupted(app);saved.finishWrite(output);output=null;}
            catch(IOException|RuntimeException failure){if(output!=null)saved.failWrite(output);throw failure;}
            return readable.append('\n').append(app.getString(R.string.native_preferences_test_report_saved)).toString();
        } catch (org.json.JSONException e) {
            throw new IOException(app.getString(R.string.native_actions_invalid_result),e);
        } catch (LinkageError e) {
            throw new IOException(app.getString(R.string.native_actions_engine_unavailable), e);
        } catch (RuntimeException e) {
            throw new IOException(app.getString(R.string.native_actions_native_error, message(e)), e);
        }
    }

    /** The UI saves the returned actual level, because Orca may enforce a minimum. */
    static String setLogLevel(String level) throws IOException {
        requireWorker();
        try { return ExperimentalSlicer.setNativeLogLevel(level); }
        catch (LinkageError | RuntimeException e) { throw new IOException(message(e), e); }
    }

    private static String cloneName(Context app, String sourceName) {
        String base = sourceName == null ? "Model" : sourceName;
        int dot = base.lastIndexOf('.');
        if (dot > 0) base = base.substring(0, dot);
        return app.getString(R.string.native_actions_clone_name, base);
    }

    private static void requireUnchanged(Context app, CurrentModelStore.Snapshot source, EngineProfileSession session) throws IOException {
        interrupted(app);
        if (!source.selectionKey.equals(CurrentModelStore.selectionKey(app)))
            throw new IOException(app.getString(R.string.native_actions_model_changed));
        if (!session.stillCurrent(app)) throw new IOException(app.getString(R.string.native_actions_profiles_changed));
    }
    private static void requireWorker() {
        if (Looper.myLooper() == Looper.getMainLooper()) throw new IllegalStateException("Native preference actions require a worker thread");
    }
    private static void interrupted(Context app) throws InterruptedIOException {
        if (Thread.currentThread().isInterrupted()) throw new InterruptedIOException(app.getString(R.string.native_actions_canceled));
    }
    private static String message(Throwable failure) {
        String value = failure.getMessage();
        return value == null || value.isEmpty() ? failure.getClass().getSimpleName() : value;
    }
    private static void deletePrivateJob(File file) {
        if (file.isDirectory()) {
            File[] children = file.listFiles();
            if (children != null) for (File child : children) deletePrivateJob(child);
        }
        file.delete();
    }
}
